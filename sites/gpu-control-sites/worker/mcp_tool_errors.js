const RUNPOD_PUBLIC_ERROR_CODES = new Set([
  "RUNPOD_AUTHENTICATION_FAILED", "RUNPOD_PERMISSION_DENIED", "RUNPOD_PROVIDER_NOT_CONFIGURED",
  "RUNPOD_PROVIDER_TIMEOUT", "RUNPOD_PROVIDER_UNAVAILABLE", "RUNPOD_RATE_LIMITED",
  "RUNPOD_ENDPOINT_CONFIGURATION_MISMATCH", "RUNPOD_CATALOG_PRICE_INVALID_OR_ABOVE_MAXIMUM",
  "RUNPOD_NETWORK_ERROR",
]);

/** Map internal tool failures to the stable, deliberately bounded MCP error contract. */
export function mcpToolErrorCode(error) {
  if (PUBLIC_TOOL_ERROR_CODES.has(error?.message)) return error.message;
  if (error?.name === "RunpodProviderError" && RUNPOD_PUBLIC_ERROR_CODES.has(error?.code)) return error.code;
  if (typeof error?.message === "string" && error.message.startsWith("GATEWAY_DELEGATION_")) {
    return "GATEWAY_DELEGATION_FAILED";
  }
  return "INTERNAL_ERROR";
}
